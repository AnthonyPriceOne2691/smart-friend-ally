/// Расстановщик ударений (настоящий — RUAccent, V3). Вход — фраза в исходном написании; ответ — та же фраза с «+» перед
/// ударной гласной каждого слова, где ударение известно (формат RUAccent). «ё» расстановщик может восстановить; другие
/// правки его ответа дойдут до движка, а экран и журнал получают фразу как есть.
public protocol StressPlacer: Sendable {
    func place(_ text: String) throws -> String
}
