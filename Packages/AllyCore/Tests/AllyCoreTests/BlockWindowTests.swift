final class BlockWindowTests: XCTestCase {
    func testTheWindowKeepsHerNameInAThirdOfTheBlocksD1Replies() async {  // M40
        let rig = Rig(replies: BlockD1.turns.map(\.elly), router: RouterRouting(),
                      names: FamilyNames(her: "Соня", brothers: ["Тёма"]))
        await rig.session.handle(.wake)
        for turn in BlockD1.turns { await rig.hear(turn.her) }
        let said = rig.model.memory.turns.map { $0.said ?? "" }
        let named = said.indices.filter { said[$0].range(of: "Сон[яеиюь]", options: .regularExpression) != nil }
        XCTAssertEqual(said.count, 31)
        XCTAssertEqual(BlockD1.turns.filter { $0.elly.contains("Сон") }.count, 23)
        XCTAssertEqual(named.map { $0 + 1 }, [6, 7, 9, 13, 15, 18, 21, 24, 27, 30])  // 10 of 31: a third
    }
}
